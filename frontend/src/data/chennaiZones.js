export function getZoneByNameOrId(identifier) {
  if (!identifier) return null;
  const clean = identifier.trim().toLowerCase();
  return CHENNAI_ZONES.find(
    z => z.id.toLowerCase() === clean || z.name.toLowerCase() === clean || clean.includes(z.name.toLowerCase()) || z.name.toLowerCase().includes(clean)
  ) || null;
}

export function getWardsForZone(zoneNameOrId) {
  const zone = getZoneByNameOrId(zoneNameOrId);
  return zone ? zone.wards : [];
}

